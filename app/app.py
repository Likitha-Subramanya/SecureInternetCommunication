@app.route("/send", methods=["GET", "POST"])
def send_message():

    if "user_id" not in session:
        return redirect(url_for("login"))

    connection = get_db_connection()
    cursor = connection.cursor()

    # Get all users except current user
    cursor.execute(
        """
        SELECT username
        FROM users
        WHERE username != %s
        ORDER BY username
        """,
        (session["username"],)
    )

    users = cursor.fetchall()

    if request.method == "POST":

        receiver = request.form["receiver"].strip()
        message = request.form["message"].strip()

        if not receiver or not message:
            cursor.close()
            connection.close()

            return "Receiver and message are required."

        # Verify receiver exists
        cursor.execute(
            """
            SELECT username
            FROM users
            WHERE username = %s
            """,
            (receiver,)
        )

        receiver_exists = cursor.fetchone()

        if not receiver_exists:

            cursor.close()
            connection.close()

            return "Receiver does not exist."

        # Get the unique request ID generated by the browser
        request_id = request.form.get("request_id", "").strip()

        if not request_id:
            cursor.close()
            connection.close()

            return "Security Error: Missing request ID."
        # Check whether this request ID was already processed
        cursor.execute(
            """
            SELECT id
            FROM messages
            WHERE request_id = %s
            """,
            (request_id,)
        )

        existing_request = cursor.fetchone()

        if existing_request:
            cursor.close()
            connection.close()

            return "Security Error: Replay attack detected."
        # Generate AES-256 key
        aes_key = generate_aes_key()

        # Load persistent RSA-2048 keys
        private_key, public_key = load_or_generate_keys()

        # Encrypt message using AES-256-GCM
        nonce, encrypted_message = encrypt_message(
            message,
            aes_key
        )

        # Protect AES key using RSA-2048
        encrypted_aes_key = encrypt_aes_key(
            aes_key,
            public_key
        )

        # Generate HMAC-SHA256
        message_hmac = generate_hmac(
            encrypted_message,
            aes_key
        )

        # Verify integrity before storing
        integrity_verified = verify_hmac(
            encrypted_message,
            message_hmac,
            aes_key
        )

        # Store encrypted message
        cursor.execute(
            """
            INSERT INTO messages
            (
                sender,
                receiver,
                request_id,
                encrypted_message,
                nonce,
                encrypted_aes_key,
                hmac
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            """,
            (
                session["username"],
                receiver,
                request_id,
                encrypted_message.hex(),
                nonce.hex(),
                encrypted_aes_key.hex(),
                message_hmac.hex()
            )
        )

        connection.commit()

        cursor.close()
        connection.close()

        return render_template(
            "message_result.html",
            sender=session["username"],
            receiver=receiver,
            integrity_verified=integrity_verified,
            encrypted_message=encrypted_message.hex(),
            encrypted_aes_key=encrypted_aes_key.hex(),
            message_hmac=message_hmac.hex()
        )

    cursor.close()
    connection.close()

    return render_template(
        "send.html",
        username=session["username"],
        users=users
    )


