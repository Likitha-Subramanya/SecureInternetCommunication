@app.route("/inbox")
def inbox():

    if "user_id" not in session:
        return redirect(url_for("login"))

    private_key, public_key = load_or_generate_keys()

    connection = get_db_connection()
    cursor = connection.cursor()

    cursor.execute(
        """
        SELECT
            id,
            sender,
            receiver,
            encrypted_message,
            nonce,
            encrypted_aes_key,
            hmac,
            created_at
        FROM messages
        WHERE receiver = %s
        ORDER BY id DESC
        """,
        (session["username"],)
    )

    stored_messages = cursor.fetchall()

    cursor.close()
    connection.close()

    decrypted_messages = []

    for stored_message in stored_messages:

        try:

            message_id = stored_message[0]
            sender = stored_message[1]
            receiver = stored_message[2]

            encrypted_message = bytes.fromhex(
                stored_message[3]
            )

            nonce = bytes.fromhex(
                stored_message[4]
            )

            encrypted_aes_key = bytes.fromhex(
                stored_message[5]
            )

            received_hmac = bytes.fromhex(
                stored_message[6]
            )

            created_at = stored_message[7]

            # Recover AES key using RSA private key
            aes_key = decrypt_aes_key(
                encrypted_aes_key,
                private_key
            )

            # Verify message integrity
            integrity_verified = verify_hmac(
                encrypted_message,
                received_hmac,
                aes_key
            )

            if integrity_verified:

                decrypted_message = decrypt_message(
                    nonce,
                    encrypted_message,
                    aes_key
                )

            else:

                decrypted_message = (
                    "Security Error: "
                    "Message integrity verification failed."
                )

            decrypted_messages.append(
                {
                    "id": message_id,
                    "sender": sender,
                    "receiver": receiver,
                    "message": decrypted_message,
                    "created_at": created_at,
                    "integrity_verified": integrity_verified
                }
            )

        except Exception:

            decrypted_messages.append(
                {
                    "id": stored_message[0],
                    "sender": stored_message[1],
                    "receiver": stored_message[2],
                    "message": "Decryption failed.",
                    "created_at": stored_message[7],
                    "integrity_verified": False
                }
            )

    return render_template(
        "receive.html",
        messages=decrypted_messages,
        username=session["username"]
    )


